export default function HomeNav({ active }: Props) {
  const navigate = useNavigate()

  const items = [
    { key: 'trips' as const, label: 'TRIPS', icon: <BookIcon />, path: '/' },
    { key: 'explore' as const, label: 'EXPLORE', icon: <CompassIcon />, path: '/explore' },
    { key: 'settings' as const, label: 'SETTINGS', icon: <GearIcon />, path: '/settings' },
  ]

  return (
    <nav className="bottom-nav home-nav">
      {items.map(({ key, label, icon, path }) => (
        <button
          key={key}
          className={`nav-item ${active === key ? 'active' : ''}`}
          onClick={() => navigate(path)}
        >
          <div className="nav-icon">{icon}</div>
          <span>{label}</span>
        </button>
      ))}
    </nav>
  )
}
